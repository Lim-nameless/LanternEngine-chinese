def main():
    key = sys.argv[1] if len(sys.argv) > 1 else ""
    text = MSG.get(key)
    if text is None:
        print(f"（未知提示键 {key}）")
        return 1
    sys.stdout.write(text.lstrip("\n"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
